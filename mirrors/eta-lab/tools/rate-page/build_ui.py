#!/usr/bin/env python3
"""Generate rate-ui.js (an ES module in the style of kit/lab-viewer/worker/ui.js) from rate.css + rate.js:
   export const RATE_CSS, RATE_JS; export function rateShell(nonce) -> the full HTML page for GET /rate.
The page needs the viewer's own CSP (default-src 'none'; script-src/style-src nonce; connect-src 'self'): no fonts, no inline style
attributes, no external request. Run:  python3 build_ui.py   (writes rate-ui.js next to it)"""
import pathlib
here = pathlib.Path(__file__).parent
css = (here / "rate.css").read_text()
js = (here / "rate.js").read_text()
for name, s in (("rate.css", css), ("rate.js", js)):
    assert "`" not in s and "${" not in s, name + ": a backtick or ${ would break the template literal"
assert "\\" not in css, "rate.css: backslash"
out = ("// GENERATED by tools/rate-page/build_ui.py from rate.css + rate.js: edit those, not this file.\n"
       "export const RATE_CSS = `\n" + css + "`;\n\n"
       "export const RATE_JS = String.raw`\n" + js + "`;\n\n"
       "export function rateShell(nonce) {\n"
       "  return `<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
       "<meta name=\"robots\" content=\"noindex,nofollow\"><title>Rating</title><style nonce=\"${nonce}\">${RATE_CSS}</style></head><body>"
       "<header><h1>Transcript rating <span class=\"prog\" id=\"prog\"></span></h1><div class=\"pbar\" aria-hidden=\"true\"><i id=\"pfill\"></i></div><nav id=\"sets\"></nav></header>"
       "<main><div id=\"intro\"></div><div id=\"panel\"><p class=\"empty\">Loading…</p></div>"
       "<div class=\"nav\"><button id=\"prev\" type=\"button\">Previous</button><button id=\"next\" class=\"pri\" type=\"button\">Next</button></div>"
       "<div class=\"nav2\"><button id=\"nextopen\" class=\"link\" type=\"button\">Next open item</button>"
       "<label for=\"jump\">Go to <select id=\"jump\" aria-label=\"Go to item\"></select></label>"
       "<label for=\"auto\"><input type=\"checkbox\" id=\"auto\"> Move on after I answer</label></div>"
       "<div class=\"status\" id=\"status\" aria-live=\"polite\"></div><div class=\"status\" id=\"done\" aria-live=\"polite\"></div></main>"
       "<script nonce=\"${nonce}\">${RATE_JS}</script></body></html>`;\n}\n")
(here / "rate-ui.js").write_text(out)
print("wrote rate-ui.js", len(out), "bytes")
