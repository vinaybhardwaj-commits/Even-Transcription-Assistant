#!/usr/bin/env python3
"""Generate worker/roadmap_docs.js: a snapshot of docs/ROADMAP.md and docs/DECISIONS.md baked into the Worker bundle (FABLE 459.5).

The /roadmap page renders these embedded bytes server-side (no client script, no external fetch); refreshing the shown content means
re-running this tool on a fresh main and redeploying - the page itself states the source shas so a reader can tell the snapshot's age.
Run from anywhere; `--check` exits 1 if the generated file is out of date."""
import hashlib, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DOCS = {"roadmap": "docs/ROADMAP.md", "decisions": "docs/DECISIONS.md"}


def build():
    out = {}
    for key, rel in DOCS.items():
        data = (ROOT / rel).read_bytes()
        text = data.decode("utf-8")
        out[key] = {"src": rel, "sha256": hashlib.sha256(data).hexdigest(), "text": text}
    return ("// GENERATED by tools/embed_roadmap.py from docs/ROADMAP.md and docs/DECISIONS.md (deploy-time snapshot of main); do not edit.\n"
            "export const DOCS = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n")


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "worker" / "roadmap_docs.js"
    new = build()
    if "--check" in sys.argv:
        sys.exit(0 if target.exists() and target.read_text() == new else 1)
    target.write_text(new)
    print(f"wrote {target} ({len(new)} bytes)")
