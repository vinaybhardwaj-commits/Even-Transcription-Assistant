#!/usr/bin/env python3
"""Generate worker/rate_pages.js from surg-page's tested single-file pages (tools/segment-label/page.html, tools/readability-rate/page.html).

The pages are used UNCHANGED except: the Google Fonts <link> tags are dropped (the viewer's CSP allows no external request), <style>/<script>
get the per-response nonce, and a small shim is inserted before the page script that answers the page's `claude.use("db"|"user")` calls
from /api/rate/<set>/rows and /api/rate/<set>/mine. Run from anywhere; `--check` exits 1 if the generated file is out of date."""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SETS = {"label200": ("tools/segment-label/page.html", "rows", "labels"), "rate20": ("tools/readability-rate/page.html", "excerpts", "ratings")}
SHIM = r"""(()=>{const C=window.__RATE,J=async(u,o)=>{const r=await fetch(u,o);if(!r.ok){const e=new Error("http "+r.status);e.code=r.status===422?"invalid_argument":"http";throw e}return r.json()};
const snap=rows=>({docs:rows.map(x=>({exists:true,id:x.id,data:()=>x}))});
const db={collection:n=>({onSnapshot:(cb,err)=>{if(n!==C.rows)return()=>{};J("/api/rate/"+C.set+"/rows").then(j=>cb(snap(j.rows)),e=>err&&err(e));return()=>{}}}),
 doc:()=>({get:async()=>{const d=await J("/api/rate/"+C.set+"/mine");return{exists:Object.keys(d.t||{}).length>0,data:()=>d}},
  set:async b=>{await J("/api/rate/"+C.set+"/mine",{method:"PUT",headers:{"content-type":"application/json"},body:JSON.stringify({t:b.t})})}})};
const user={me:async()=>{let who="";try{who=(await J("/api/rate/"+C.set+"/mine")).rater||""}catch(e){}return{id:"me",name:who,isOwner:false}},profiles:async()=>({})};
window.claude={use:async n=>n==="db"?db:n==="user"?user:null}})();"""


def build():
    out = {}
    for name, (rel, rows, answers) in SETS.items():
        html = (ROOT / rel).read_text()
        html = re.sub(r"<link\b[^>]*>\s*", "", html)
        assert "<script>" in html and "<style>" in html, rel
        cfg = f'<script nonce="__NONCE__">window.__RATE={json.dumps({"set": name, "rows": rows, "answers": answers})};{SHIM}</script>\n'
        html = html.replace("<style>", '<style nonce="__NONCE__">', 1)
        html = html.replace("<script>", cfg + '<script nonce="__NONCE__">', 1)
        if not html.lstrip().lower().startswith("<!doctype"):
            html = '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">' + html
        out[name] = html
    return "// GENERATED by tools/embed_rate_pages.py from tools/segment-label/page.html and tools/readability-rate/page.html; do not edit.\nexport const PAGES = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n"


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "worker" / "rate_pages.js"
    new = build()
    if "--check" in sys.argv:
        sys.exit(0 if target.exists() and target.read_text() == new else 1)
    target.write_text(new)
    print(f"wrote {target} ({len(new)} bytes)")
